class Solution {
public:
    long long countCommas(long long n) {
        //1 to 10^3-1
        if(n<=999)return 0;
        //10^4 to 10^6-1
        else if(n<=999999) return 1*(n-999);
        //10^7 to 10^9-1
        else if(n<=999999999) return 2*(n-999999)+1*(999999-999);
        //10^10 to 10^12-1
        else if(n<=999999999999) return 3*(n-999999999)+2*(999999999-999999)+1*(999999-999);
        //10^13 to 10^15-1
        else if(n<=999999999999999) return 4*(n-999999999999)+3*(999999999999-999999999)+2*(999999999-999999)+1*(999999-999);
        //10^15
        else return 4*(n-1-999999999999)+3*(999999999999-999999999)+2*(999999999-999999)+1*(999999-999)+5;
    }
};